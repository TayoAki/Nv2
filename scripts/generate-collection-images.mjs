// Writes src/api/catalog/capsuleImages.ts from the photos in assets/collection.
// Name each file after its capsule key: `<key>.png` (cut-out) is preferred over
// `<key>.webp` / `<key>.jpg` (house photo). Run with `npm run collection`.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/collection');
const rank = { png: 0, webp: 1, jpg: 2, jpeg: 2 };

const best = new Map();
for (const file of readdirSync(dir)) {
  const match = /^(.+)\.(png|webp|jpe?g)$/i.exec(file);
  if (!match) continue;
  const [, key, ext] = match;
  const current = best.get(key);
  if (!current || rank[ext.toLowerCase()] < rank[current.ext]) best.set(key, { file, ext: ext.toLowerCase() });
}

const entries = [...best.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, { file }]) => `  '${key}': require('@/assets/collection/${file}'),`);

writeFileSync(
  join(root, 'src/api/catalog/capsuleImages.ts'),
  `// Generated by scripts/generate-collection-images.mjs. Do not edit by hand:
// add photos to assets/collection and run \`npm run collection\`.
export const capsuleImages: Record<string, number> = ${entries.length ? `{\n${entries.join('\n')}\n}` : '{}'};
`,
);
console.log(`Wrote ${entries.length} capsule images to src/api/catalog/capsuleImages.ts`);
